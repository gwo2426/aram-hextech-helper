// 按登场率排序
export const championsByPickRate = [...allChampions].sort((a, b) => b.pickRate - a.pickRate);

// 按职业筛选
export function getChampionsByRole(role: string): Champion[] {
  return allChampions.filter(champ => champ.role.includes(role));
}

// 按等级筛选
export function getChampionsByTier(tier: string): Champion[] {
  return allChampions.filter(champ => champ.tier === tier);
}

// 搜索英雄
export function searchChampions(query: string): Champion[] {
  const lowerQuery = query.toLowerCase();
  return allChampions.filter(champ => 
    champ.name.toLowerCase().includes(lowerQuery) ||
    champ.nameEn.toLowerCase().includes(lowerQuery)
  );
}
